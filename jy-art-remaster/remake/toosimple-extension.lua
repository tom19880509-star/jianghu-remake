 local applied={arts=0,panels=0}

 local function artPristine(p,slot1,lv1)
  if p['武功1']~=slot1 or p['武功等级1']~=lv1 then return false end
  for i=2,10 do if p['武功'..i]~=0 then return false end end
  return true
 end

 local function panelPristine(p,want)
  for k,v in pairs(want) do if p[k]~=v then return false end end
  return true
 end

 local function seed()
  applied={arts=0,panels=0}
  for pid,row in pairs(ARTS) do
   local p=JY.Person[pid]
   if p and artPristine(p,row.slot1,row.lv1) then
    for _,a in ipairs(row.add) do p['武功'..a[1]]=a[2];p['武功等级'..a[1]]=a[3];applied.arts=applied.arts+1 end
   end
  end
  for pid,row in pairs(PANELS) do
   local p=JY.Person[pid]
   if p and panelPristine(p,PRISTINE[pid]) then
    for k,v in pairs(row) do p[k]=v end;applied.panels=applied.panels+1
   end
  end
 end

